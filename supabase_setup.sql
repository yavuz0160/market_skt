-- 1. 'urunler' Tablosunu Oluşturma
create table if not exists public.urunler (
    id bigint generated by default as identity primary key,
    urun_adi text not null,
    skt date not null,
    kalan_adet integer not null default 1,
    resim_url text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. 'market_images' Public Storage Bucket Oluşturma
insert into storage.buckets (id, name, public)
values ('market_images', 'market_images', true)
on conflict (id) do nothing;

-- 3. RLS (Row Level Security) Politikaları (MVP / Anon Key ile sorunsuz çalışması için)
alter table public.urunler enable row level security;

create policy "Tablo okuma/yazma/silme izni (MVP)"
on public.urunler
for all
to anon, authenticated
using (true)
with check (true);

create policy "Storage yükleme/okuma/silme izni (MVP)"
on storage.objects
for all
to anon, authenticated
using (bucket_id = 'market_images')
with check (bucket_id = 'market_images');

